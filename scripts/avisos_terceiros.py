"""Regenerate THIRD_PARTY_NOTICES.md and third_party_licenses/ from the installed, pinned packages.

Run it with the venv that was installed from requirements.txt, from the project folder:
    python scripts/avisos_terceiros.py
It copies each package's own licence files, so the texts the LGPL and MPL ask to ship are included.
"""
import importlib.metadata as md
import re
import shutil
from pathlib import Path

RAIZ = Path(__file__).resolve().parent.parent
DESTINO = RAIZ / "third_party_licenses"
FICHEIRO_LICENCA = re.compile(r"(LICEN[CS]E|COPYING|NOTICE|AUTHORS)", re.I)


def pacotes():
    for linha in (RAIZ / "requirements.txt").read_text(encoding="utf-8-sig").splitlines():
        if "==" in linha and not linha.startswith("#"):
            nome, versao = (p.strip() for p in linha.split("=="))
            yield nome, versao


def licenca(meta):
    texto = meta.get("License-Expression") or ""
    if not texto:
        classificadores = [c.split("::")[-1].strip() for c in meta.get_all("Classifier") or [] if c.startswith("License ::")]
        texto = ", ".join(classificadores) or (meta.get("License") or "").splitlines()[0]
    return texto


def main():
    shutil.rmtree(DESTINO, ignore_errors=True)
    linhas = []
    for nome, versao in pacotes():
        dist = md.distribution(nome)
        if dist.version != versao:
            raise SystemExit(f"{nome}: installed {dist.version}, pinned {versao}. Install requirements.txt first.")
        copiados = []
        for ficheiro in dist.files or []:
            if "dist-info" in str(ficheiro) and FICHEIRO_LICENCA.search(ficheiro.name):
                alvo = DESTINO / nome / ficheiro.name
                alvo.parent.mkdir(parents=True, exist_ok=True)
                alvo.write_bytes(Path(dist.locate_file(ficheiro)).read_bytes())
                copiados.append(f"[{ficheiro.name}](third_party_licenses/{nome}/{ficheiro.name})")
        url = dist.metadata.get("Home-page") or next(
            (u.split(",", 1)[1].strip() for u in dist.metadata.get_all("Project-URL") or []
             if u.lower().startswith(("source", "homepage", "repository"))), "")
        linhas.append(f"| {nome} | {versao} | {licenca(dist.metadata)} | {url} | {', '.join(copiados)} |")
    (RAIZ / "THIRD_PARTY_NOTICES.md").write_text(
        "# Third-party notices\n\n"
        "This software uses the packages below, installed unmodified from PyPI with `pip`. Their copyright "
        "belongs to their authors. Each package's licence text is copied in `third_party_licenses/`.\n\n"
        "- **LGPL-3.0** (python-telegram-bot, psycopg, psycopg-binary): used unmodified as separate, replaceable "
        "libraries; their source is available at the links below.\n"
        "- **MPL-2.0** (certifi): used unmodified; its source is available at the link below.\n"
        "- `psycopg-binary` also bundles compiled libraries (libpq, OpenSSL) under their own licences; see its "
        "project page.\n\n"
        "Generated by `scripts/avisos_terceiros.py` from `requirements.txt`. Regenerate it after updating the pins.\n\n"
        "| Package | Version | Licence | Source | Licence files |\n| --- | --- | --- | --- | --- |\n"
        + "\n".join(linhas) + "\n", encoding="utf-8")
    print(f"{len(linhas)} packages written")


if __name__ == "__main__":
    main()
